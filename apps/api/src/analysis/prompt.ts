export function buildUserPrompt(query: ProductQuery): string {
  if (query.kind === 'url') {
    return `다음 링크의 제품을 분석해 주세요.\n${query.value}`;
  }
  return `다음 제품을 분석해 주세요.\n제품명: ${query.value}`;
}
